public class Class {
        int id;
        String name;
        public static void main(String[] args) {
            Class c1 = new Class();
            c1.id = 100;
            c1.name = "Akash";
            System.out.println("Class id: " + c1.id);
            System.out.println("Class name: " + c1.name);
        }
}
