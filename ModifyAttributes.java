public class ModifyAttributes {
    int id;
    String name;
    public static void main(String[] args) {
        ModifyAttributes c1 = new ModifyAttributes();
        c1.id = 100;
        c1.name = "Akash";
        System.out.println("id: " + c1.id);
        System.out.println("name: " + c1.name);
    }
}
